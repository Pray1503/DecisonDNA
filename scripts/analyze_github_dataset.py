import argparse
import json
import re

from collections import Counter
from pathlib import Path


RAW_DATA_DIRECTORY = Path("data/raw/github")

REFERENCE_PATTERN = re.compile(r"(?<![\w])#(\d+)\b")


# ============================================================
# DATASET LOADING
# ============================================================


def load_json(file_path: Path):
    """
    Load one JSON file from disk.
    """

    if not file_path.exists():
        raise FileNotFoundError(
            f"Dataset file not found: {file_path}"
        )

    with file_path.open(
        "r",
        encoding="utf-8",
    ) as file:
        return json.load(file)


def load_github_dataset(
    owner: str,
    repo: str,
) -> dict:
    """
    Load the complete raw GitHub dataset
    generated by the ingestion pipeline.
    """

    repository_directory = (
        RAW_DATA_DIRECTORY
        / owner
        / repo
    )

    files_to_load = {
        "repository":
            "repository/metadata.json",

        "issues":
            "issues/issues.json",

        "issue_comments":
            "issues/comments.json",

        "issue_timelines":
            "issues/timelines.json",

        "pull_requests":
            "pull_requests/pull_requests.json",

        "pr_comments":
            "pull_requests/comments.json",

        "pr_commits":
            "pull_requests/commits.json",

        "decision_documents":
            "documents/documents.json",
    }

    dataset = {}

    for dataset_name, relative_path in files_to_load.items():

        file_path = (
            repository_directory
            / relative_path
        )

        dataset[dataset_name] = load_json(
            file_path
        )

    return dataset


