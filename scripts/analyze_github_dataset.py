def profile_dataset(dataset: dict) -> dict:
    """
    Measure and summarize the raw GitHub dataset.

    This function does NOT:
    - modify raw data
    - normalize artifacts
    - correlate semantic artifacts
    - extract decisions
    - call an LLM
    """

    issues = dataset["issues"]
    issue_comments = dataset["issue_comments"]
    issue_timelines = dataset["issue_timelines"]

    pull_requests = dataset["pull_requests"]
    pr_comments = dataset["pr_comments"]
    pr_commits = dataset["pr_commits"]

    decision_documents = dataset["decision_documents"]

    # --------------------------------------------------
    # ISSUE PROFILING
    # --------------------------------------------------

    issues_with_body = sum(
        1
        for issue in issues
        if (issue.get("body") or "").strip()
    )

    issues_without_body = (
        len(issues) - issues_with_body
    )

    total_issue_comments = sum(
        len(comments)
        for comments in issue_comments.values()
    )

    issue_comment_counts = [
        len(
            issue_comments.get(
                str(issue["number"]),
                [],
            )
        )
        for issue in issues
    ]

    issues_with_comments = sum(
        1
        for count in issue_comment_counts
        if count > 0
    )

    issues_without_comments = (
        len(issues) - issues_with_comments
    )

    # --------------------------------------------------
    # TIMELINE PROFILING
    # --------------------------------------------------

    timeline_event_types = Counter()

    total_timeline_events = 0

    issue_timeline_counts = []

    for issue in issues:

        issue_number = str(issue["number"])

        events = issue_timelines.get(
            issue_number,
            [],
        )

        issue_timeline_counts.append(
            len(events)
        )

        total_timeline_events += len(events)

        for event in events:

            event_type = event.get(
                "event",
                "unknown",
            )

            timeline_event_types[event_type] += 1

    # --------------------------------------------------
    # PULL REQUEST PROFILING
    # --------------------------------------------------

    prs_with_body = sum(
        1
        for pull_request in pull_requests
        if (pull_request.get("body") or "").strip()
    )

    prs_without_body = (
        len(pull_requests) - prs_with_body
    )

    merged_prs = sum(
        1
        for pull_request in pull_requests
        if pull_request.get("merged_at") is not None
    )

    closed_unmerged_prs = (
        len(pull_requests) - merged_prs
    )

    total_pr_comments = sum(
        len(comments)
        for comments in pr_comments.values()
    )

    pr_comment_counts = [
        len(
            pr_comments.get(
                str(pull_request["number"]),
                [],
            )
        )
        for pull_request in pull_requests
    ]

    prs_with_comments = sum(
        1
        for count in pr_comment_counts
        if count > 0
    )

    prs_without_comments = (
        len(pull_requests) - prs_with_comments
    )

    total_pr_commits = sum(
        len(commits)
        for commits in pr_commits.values()
    )

    pr_commit_counts = [
        len(
            pr_commits.get(
                str(pull_request["number"]),
                [],
            )
        )
        for pull_request in pull_requests
    ]

    # --------------------------------------------------
    # DOCUMENT PROFILING
    # --------------------------------------------------

    document_types = Counter()

    empty_documents = 0

    total_document_characters = 0

    document_character_counts = []

    likely_noise = []

    for document in decision_documents:

        document_type = document.get(
            "document_type",
            "unknown",
        )

        document_types[document_type] += 1

        content = (
            document.get("content")
            or ""
        ).strip()

        content_length = len(content)

        document_character_counts.append(
            content_length
        )

        if not content:
            empty_documents += 1

        total_document_characters += content_length

        path = (
            document.get("path")
            or ""
        ).lower()

        if (
            "template" in path
            or path.endswith("/index.md")
            or path.endswith("/index.mdx")
        ):
            likely_noise.append(
                document.get("path")
            )

    return {
        "issues": {
            "total": len(issues),
            "with_body": issues_with_body,
            "without_body": issues_without_body,
            "with_comments": issues_with_comments,
            "without_comments": issues_without_comments,
            "total_comments": total_issue_comments,
            "comments_per_issue": issue_comment_counts,
        },

        "timelines": {
            "total_events": total_timeline_events,
            "events_per_issue": issue_timeline_counts,
            "event_types": dict(
                timeline_event_types.most_common()
            ),
        },

        "pull_requests": {
            "total": len(pull_requests),
            "with_body": prs_with_body,
            "without_body": prs_without_body,
            "merged": merged_prs,
            "closed_unmerged": closed_unmerged_prs,
            "with_comments": prs_with_comments,
            "without_comments": prs_without_comments,
            "total_comments": total_pr_comments,
            "comments_per_pr": pr_comment_counts,
            "total_commits": total_pr_commits,
            "commits_per_pr": pr_commit_counts,
        },

        "documents": {
            "total": len(decision_documents),
            "document_types": dict(
                document_types.most_common()
            ),
            "empty_documents": empty_documents,
            "total_characters": total_document_characters,
            "characters_per_document":
                document_character_counts,
            "likely_noise": likely_noise,
        },
    }


