def extract_number_references(
    text: str | None,
) -> set[str]:
    """
    Extract local GitHub references such as:

    #123
    #456

    Example:

    "Fixes #123 and relates to #456"

    Returns:

    {"123", "456"}
    """

    if not text:
        return set()

    return set(
        REFERENCE_PATTERN.findall(text)
    )


def build_reference_index(
    dataset: dict,
) -> dict[str, str]:
    """
    Build an index of issue/PR numbers that exist
    in the currently collected dataset.

    Example:

    {
        "123": "issue",
        "456": "pull_request",
    }
    """

    reference_index = {}

    for issue in dataset["issues"]:

        reference_index[
            str(issue["number"])
        ] = "issue"

    for pull_request in dataset["pull_requests"]:

        reference_index[
            str(pull_request["number"])
        ] = "pull_request"

    return reference_index


def resolve_reference_type(
    target_number: str,
    reference_index: dict[str, str],
) -> str:
    """
    Resolve a GitHub number to its known artifact type.

    If the referenced number is outside our collected
    sample, preserve it as unresolved rather than
    incorrectly assuming it is an issue or PR.
    """

    return reference_index.get(
        str(target_number),
        "unresolved_github_number",
    )


def create_relationship(
    source_type: str,
    source_id: str,
    relationship_type: str,
    target_type: str,
    target_id: str,
    evidence_source: str,
    evidence_text: str | None = None,
    evidence_url: str | None = None,
) -> dict:
    """
    Create one standardized deterministic
    relationship record.
    """

    return {
        "source_type": source_type,
        "source_id": str(source_id),

        "relationship_type": relationship_type,

        "target_type": target_type,
        "target_id": str(target_id),

        "evidence_source": evidence_source,
        "evidence_text": evidence_text,
        "evidence_url": evidence_url,

        "method": "deterministic",
    }


def analyze_relationships(
    dataset: dict,
) -> list[dict]:
    """
    Extract deterministic relationships from
    the raw GitHub dataset.

    Relationships extracted:

    1. Issue body references.
    2. Issue comment references.
    3. PR body references.
    4. PR comment references.
    5. Commit message references.
    6. Timeline commit-reference events.
    7. PR -> commit membership.

    No LLM is used.
    """

    relationships = []

    issues = dataset["issues"]
    issue_comments = dataset["issue_comments"]
    issue_timelines = dataset["issue_timelines"]

    pull_requests = dataset["pull_requests"]
    pr_comments = dataset["pr_comments"]
    pr_commits = dataset["pr_commits"]

    reference_index = build_reference_index(
        dataset
    )

    # --------------------------------------------------
    # ISSUE BODY REFERENCES
    # --------------------------------------------------

    for issue in issues:

        issue_number = str(issue["number"])

        body = issue.get("body") or ""

        references = extract_number_references(
            body
        )

        for target_number in references:

            if target_number == issue_number:
                continue

            relationships.append(
                create_relationship(
                    source_type="issue",
                    source_id=issue_number,
                    relationship_type="references",
                    target_type=resolve_reference_type(
                        target_number,
                        reference_index,
                    ),
                    target_id=target_number,
                    evidence_source="issue_body",
                    evidence_text=body,
                    evidence_url=issue.get("html_url"),
                )
            )

    # --------------------------------------------------
    # ISSUE COMMENT REFERENCES
    # --------------------------------------------------

    for issue_number, comments in (
        issue_comments.items()
    ):

        for comment in comments:

            body = comment.get("body") or ""

            references = extract_number_references(
                body
            )

            for target_number in references:

                if target_number == str(issue_number):
                    continue

                relationships.append(
                    create_relationship(
                        source_type="issue",
                        source_id=issue_number,
                        relationship_type="references",
                        target_type=resolve_reference_type(
                            target_number,
                            reference_index,
                        ),
                        target_id=target_number,
                        evidence_source="issue_comment",
                        evidence_text=body,
                        evidence_url=comment.get("html_url"),
                    )
                )

    # --------------------------------------------------
    # PR BODY REFERENCES
    # --------------------------------------------------

    for pull_request in pull_requests:

        pull_number = str(
            pull_request["number"]
        )

        body = (
            pull_request.get("body")
            or ""
        )

        references = extract_number_references(
            body
        )

        for target_number in references:

            if target_number == pull_number:
                continue

            relationships.append(
                create_relationship(
                    source_type="pull_request",
                    source_id=pull_number,
                    relationship_type="references",
                    target_type=resolve_reference_type(
                        target_number,
                        reference_index,
                    ),
                    target_id=target_number,
                    evidence_source="pr_body",
                    evidence_text=body,
                    evidence_url=pull_request.get("html_url"),
                )
            )

    # --------------------------------------------------
    # PR COMMENT REFERENCES
    # --------------------------------------------------

    for pull_number, comments in (
        pr_comments.items()
    ):

        for comment in comments:

            body = comment.get("body") or ""

            references = extract_number_references(
                body
            )

            for target_number in references:

                if target_number == str(pull_number):
                    continue

                relationships.append(
                    create_relationship(
                        source_type="pull_request",
                        source_id=pull_number,
                        relationship_type="references",
                        target_type=resolve_reference_type(
                            target_number,
                            reference_index,
                        ),
                        target_id=target_number,
                        evidence_source="pr_comment",
                        evidence_text=body,
                        evidence_url=comment.get("html_url"),
                    )
                )

    # --------------------------------------------------
    # COMMIT MESSAGE REFERENCES
    # --------------------------------------------------

    for pull_number, commits in (
        pr_commits.items()
    ):

        for commit in commits:

            commit_sha = commit.get("sha")

            if not commit_sha:
                continue

            commit_data = (
                commit.get("commit")
                or {}
            )

            commit_message = (
                commit_data.get("message")
                or ""
            )

            references = extract_number_references(
                commit_message
            )

            for target_number in references:

                relationships.append(
                    create_relationship(
                        source_type="commit",
                        source_id=commit_sha,
                        relationship_type="references",
                        target_type=resolve_reference_type(
                            target_number,
                            reference_index,
                        ),
                        target_id=target_number,
                        evidence_source="commit_message",
                        evidence_text=commit_message,
                        evidence_url=commit.get("html_url"),
                    )
                )

    # --------------------------------------------------
    # TIMELINE REFERENCED EVENTS
    # --------------------------------------------------

    for issue_number, events in (
        issue_timelines.items()
    ):

        for event in events:

            if event.get("event") != "referenced":
                continue

            commit_id = event.get("commit_id")

            # A referenced event without a commit ID
            # is preserved only when we have enough
            # source information to understand it.
            #
            # For this first deterministic version,
            # we only create commit -> issue edges.
            if not commit_id:
                continue

            relationships.append(
                create_relationship(
                    source_type="commit",
                    source_id=commit_id,
                    relationship_type="references",
                    target_type="issue",
                    target_id=issue_number,
                    evidence_source="issue_timeline",
                    evidence_text=None,
                    evidence_url=event.get("commit_url"),
                )
            )

    # --------------------------------------------------
    # PR -> COMMIT MEMBERSHIP
    # --------------------------------------------------

    for pull_number, commits in (
        pr_commits.items()
    ):

        for commit in commits:

            commit_sha = commit.get("sha")

            if not commit_sha:
                continue

            relationships.append(
                create_relationship(
                    source_type="pull_request",
                    source_id=pull_number,
                    relationship_type="contains_commit",
                    target_type="commit",
                    target_id=commit_sha,
                    evidence_source="github_api",
                    evidence_text=None,
                    evidence_url=commit.get("html_url"),
                )
            )

    return relationships


def deduplicate_relationships(
    relationships: list[dict],
) -> list[dict]:
    """
    Remove exact duplicate relationships.

    Relationships with different evidence sources
    are preserved because they represent independent
    evidence for the same connection.
    """

    unique_relationships = []

    seen = set()

    for relationship in relationships:

        key = (
            relationship["source_type"],
            relationship["source_id"],
            relationship["relationship_type"],
            relationship["target_type"],
            relationship["target_id"],
            relationship["evidence_source"],
            relationship["evidence_url"],
        )

        if key in seen:
            continue

        seen.add(key)

        unique_relationships.append(
            relationship
        )

    return unique_relationships


def summarize_relationships(
    relationships: list[dict],
) -> dict:
    """
    Produce machine-readable relationship statistics.
    """

    relationship_types = Counter(
        relationship["relationship_type"]
        for relationship in relationships
    )

    evidence_sources = Counter(
        relationship["evidence_source"]
        for relationship in relationships
    )

    target_types = Counter(
        relationship["target_type"]
        for relationship in relationships
    )

    resolved_relationships = sum(
        1
        for relationship in relationships
        if relationship["target_type"]
        != "unresolved_github_number"
    )

    unresolved_relationships = (
        len(relationships)
        - resolved_relationships
    )

    return {
        "total_relationships":
            len(relationships),

        "relationship_types":
            dict(
                relationship_types.most_common()
            ),

        "evidence_sources":
            dict(
                evidence_sources.most_common()
            ),

        "target_types":
            dict(
                target_types.most_common()
            ),

        "resolved_relationships":
            resolved_relationships,

        "unresolved_relationships":
            unresolved_relationships,
    }


def print_relationship_summary(
    relationships: list[dict],
) -> None:
    """
    Print statistics and sample relationships.
    """

    summary = summarize_relationships(
        relationships
    )

    print("\nRELATIONSHIP ANALYSIS")
    print("=" * 50)

    print(
        f"Total relationships: "
        f"{summary['total_relationships']}"
    )

    print("\nRelationship types:")

    for relationship_type, count in (
        summary["relationship_types"].items()
    ):
        print(
            f"  {relationship_type}: {count}"
        )

    print("\nEvidence sources:")

    for evidence_source, count in (
        summary["evidence_sources"].items()
    ):
        print(
            f"  {evidence_source}: {count}"
        )

    print("\nTarget types:")

    for target_type, count in (
        summary["target_types"].items()
    ):
        print(
            f"  {target_type}: {count}"
        )

    print(
        f"\nResolved relationships: "
        f"{summary['resolved_relationships']}"
    )

    print(
        f"Unresolved relationships: "
        f"{summary['unresolved_relationships']}"
    )

    print("\nFirst 20 relationships:")

    for relationship in relationships[:20]:

        print(
            f"  "
            f"{relationship['source_type']}:"
            f"{relationship['source_id']} "
            f"--{relationship['relationship_type']}--> "
            f"{relationship['target_type']}:"
            f"{relationship['target_id']} "
            f"[{relationship['evidence_source']}]"
        )


# ============================================================
# COMMAND-LINE ENTRY POINT
# ============================================================


def main():
    """
    Command-line entry point.
    """

    parser = argparse.ArgumentParser(
        description=(
            "Analyze a raw GitHub dataset "
            "collected by DecisionDNA."
        )
    )

    parser.add_argument(
        "repository",
        help="Repository in owner/repo format",
    )

    args = parser.parse_args()

    repository_parts = (
        args.repository
        .strip("/")
        .split("/")
    )

    if len(repository_parts) != 2:
        raise ValueError(
            "Repository must use owner/repo format. "
            "Example: backstage/backstage"
        )

    owner, repo = repository_parts

    print(
        f"\nLoading GitHub dataset: "
        f"{owner}/{repo}"
    )

    dataset = load_github_dataset(
        owner=owner,
        repo=repo,
    )

    verify_dataset(dataset)

    profile = profile_dataset(
        dataset
    )

    print_profile(
        profile
    )

    relationships = analyze_relationships(
        dataset
    )

    relationships = deduplicate_relationships(
        relationships
    )

    print_relationship_summary(
        relationships
    )


if __name__ == "__main__":
    main()