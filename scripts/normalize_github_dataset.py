import argparse
import json

from collections import Counter
from pathlib import Path

from app.models.artifacts import Artifact
from app.sources.github.normalizer import (
    normalize_issue,
    normalize_pull_request,
    normalize_commit,
    normalize_document,
)


RAW_DATA_DIRECTORY = Path("data/raw/github")
NORMALIZED_DATA_DIRECTORY = Path("data/normalized/github")


# ============================================================
# DATASET LOADING
# ============================================================


def load_json(file_path: Path):
    """
    Load one JSON file from disk.
    """

    if not file_path.exists():
        raise FileNotFoundError(
            f"Dataset file not found: {file_path}"
        )

    with file_path.open(
        "r",
        encoding="utf-8",
    ) as file:
        return json.load(file)


def load_github_dataset(
    owner: str,
    repo: str,
) -> dict:
    """
    Load the complete raw GitHub dataset
    generated by the ingestion pipeline.
    """

    repository_directory = (
        RAW_DATA_DIRECTORY
        / owner
        / repo
    )

    files_to_load = {
        "repository":
            "repository/metadata.json",

        "issues":
            "issues/issues.json",

        "issue_comments":
            "issues/comments.json",

        "issue_timelines":
            "issues/timelines.json",

        "pull_requests":
            "pull_requests/pull_requests.json",

        "pr_comments":
            "pull_requests/comments.json",

        "pr_commits":
            "pull_requests/commits.json",

        "decision_documents":
            "documents/documents.json",
    }

    dataset = {}

    for dataset_name, relative_path in (
        files_to_load.items()
    ):
        file_path = (
            repository_directory
            / relative_path
        )

        dataset[dataset_name] = load_json(
            file_path
        )

    return dataset


# ============================================================
# NORMALIZATION
# ============================================================


def normalize_dataset(
    dataset: dict,
    repository: str,
) -> tuple[list[Artifact], list[str]]:
    """
    Normalize all raw GitHub objects into
    universal Artifacts.

    Returns:
        - List of normalized Artifacts
        - List of conflict warnings
    """

    artifacts = []
    conflicts = []

    # --------------------------------------------------
    # NORMALIZE ISSUES
    # --------------------------------------------------

    print("\nNormalizing issues...")

    for issue in dataset["issues"]:
        artifact = normalize_issue(
            issue=issue,
            repository=repository,
        )
        artifacts.append(artifact)

    print(
        f"  Normalized {len(dataset['issues'])} issues."
    )

    # --------------------------------------------------
    # NORMALIZE PULL REQUESTS
    # --------------------------------------------------

    print("Normalizing pull requests...")

    for pull_request in dataset["pull_requests"]:
        artifact = normalize_pull_request(
            pull_request=pull_request,
            repository=repository,
        )
        artifacts.append(artifact)

    print(
        f"  Normalized "
        f"{len(dataset['pull_requests'])} "
        f"pull requests."
    )

    # --------------------------------------------------
    # NORMALIZE COMMITS (DEDUPLICATED BY SHA)
    # --------------------------------------------------

    print("Normalizing commits...")

    seen_commit_shas = {}
    commit_count = 0
    duplicate_commit_count = 0

    for pull_number, commits in (
        dataset["pr_commits"].items()
    ):
        for commit in commits:
            sha = commit.get("sha")

            if not sha:
                continue

            commit_count += 1

            if sha in seen_commit_shas:
                duplicate_commit_count += 1

                # Check for conflict: same SHA
                # but different normalized content.
                existing = seen_commit_shas[sha]
                new_artifact = normalize_commit(
                    commit=commit,
                    repository=repository,
                )

                if (
                    existing.content
                    != new_artifact.content
                ):
                    conflict_msg = (
                        f"CONFLICT: Commit {sha} "
                        f"from PR #{pull_number} "
                        f"has different content than "
                        f"previously normalized version."
                    )
                    conflicts.append(conflict_msg)
                    print(f"  WARNING: {conflict_msg}")

                continue

            artifact = normalize_commit(
                commit=commit,
                repository=repository,
            )

            seen_commit_shas[sha] = artifact
            artifacts.append(artifact)

    unique_commits = len(seen_commit_shas)

    print(
        f"  Total commits seen: {commit_count}"
    )
    print(
        f"  Unique commits: {unique_commits}"
    )
    print(
        f"  Duplicate commits skipped: "
        f"{duplicate_commit_count}"
    )

    # --------------------------------------------------
    # NORMALIZE DOCUMENTS
    # --------------------------------------------------

    print("Normalizing documents...")

    for document in dataset["decision_documents"]:
        artifact = normalize_document(
            document=document,
            repository=repository,
        )
        artifacts.append(artifact)

    print(
        f"  Normalized "
        f"{len(dataset['decision_documents'])} "
        f"documents."
    )

    return artifacts, conflicts


# ============================================================
# VALIDATION
# ============================================================


def validate_artifacts(
    artifacts: list[Artifact],
) -> tuple[bool, list[str]]:
    """
    Validate all artifacts and check for
    deterministic ID uniqueness.
    """

    errors = []

    # Check uniqueness.
    id_counts = Counter(
        artifact.artifact_id
        for artifact in artifacts
    )

    duplicates = {
        artifact_id: count
        for artifact_id, count in id_counts.items()
        if count > 1
    }

    if duplicates:
        for artifact_id, count in duplicates.items():
            errors.append(
                f"Duplicate artifact_id: "
                f"{artifact_id} (count: {count})"
            )

    # Validate Pydantic serialization round-trip.
    for artifact in artifacts:
        try:
            serialized = artifact.model_dump(
                mode="json"
            )
            Artifact.model_validate(serialized)
        except Exception as e:
            errors.append(
                f"Validation failed for "
                f"{artifact.artifact_id}: {e}"
            )

    is_valid = len(errors) == 0

    return is_valid, errors


def validate_saved_file(
    file_path: Path,
    original_artifacts: list[Artifact],
) -> tuple[bool, list[str]]:
    """
    Reload saved artifacts.json and validate
    against Pydantic and the original artifacts.
    """

    errors = []

    with file_path.open(
        "r",
        encoding="utf-8",
    ) as file:
        saved_records = json.load(file)

    # Count check.
    if len(saved_records) != len(original_artifacts):
        errors.append(
            f"Count mismatch: saved "
            f"{len(saved_records)} vs original "
            f"{len(original_artifacts)}"
        )

    # Validate each record through Pydantic.
    reloaded_artifacts = []

    for index, record in enumerate(saved_records):
        try:
            artifact = Artifact.model_validate(record)
            reloaded_artifacts.append(artifact)
        except Exception as e:
            errors.append(
                f"Reload validation failed for "
                f"record {index}: {e}"
            )

    # Check ID uniqueness in reloaded data.
    reloaded_ids = [
        a.artifact_id for a in reloaded_artifacts
    ]

    unique_reloaded = set(reloaded_ids)

    if len(reloaded_ids) != len(unique_reloaded):
        errors.append(
            "Reloaded artifacts contain "
            "duplicate IDs."
        )

    # Check deterministic stability.
    original_ids = sorted(
        a.artifact_id for a in original_artifacts
    )
    reloaded_ids_sorted = sorted(reloaded_ids)

    if original_ids != reloaded_ids_sorted:
        errors.append(
            "Reloaded artifact IDs do not match "
            "original artifact IDs."
        )

    is_valid = len(errors) == 0

    return is_valid, errors


# ============================================================
# STATISTICS
# ============================================================


def print_statistics(
    artifacts: list[Artifact],
    conflicts: list[str],
    validation_passed: bool,
    reload_passed: bool,
    output_path: Path,
) -> None:
    """
    Print normalization summary statistics.
    """

    print("\n" + "=" * 60)
    print("NORMALIZATION SUMMARY")
    print("=" * 60)

    print(f"\nTotal Artifacts: {len(artifacts)}")

    # Artifacts by type.
    type_counts = Counter(
        artifact.artifact_type.value
        for artifact in artifacts
    )

    print("\nArtifacts by Type:")

    for artifact_type, count in (
        type_counts.most_common()
    ):
        print(f"  {artifact_type}: {count}")

    # Unique IDs.
    unique_ids = set(
        artifact.artifact_id
        for artifact in artifacts
    )

    print(f"\nUnique Artifact IDs: {len(unique_ids)}")

    duplicate_count = len(artifacts) - len(unique_ids)
    print(f"Duplicate Artifact IDs: {duplicate_count}")

    print(
        f"Normalization Conflicts: {len(conflicts)}"
    )

    for conflict in conflicts:
        print(f"  - {conflict}")

    # Data quality.
    empty_content = sum(
        1 for a in artifacts
        if not (a.content or "").strip()
    )

    missing_author = sum(
        1 for a in artifacts
        if a.author is None
    )

    missing_created = sum(
        1 for a in artifacts
        if a.created_at is None
    )

    missing_updated = sum(
        1 for a in artifacts
        if a.updated_at is None
    )

    missing_url = sum(
        1 for a in artifacts
        if a.url is None
    )

    print(
        f"\nArtifacts with Empty Content: "
        f"{empty_content}"
    )
    print(
        f"Artifacts with Missing Author: "
        f"{missing_author}"
    )
    print(
        f"Artifacts with Missing created_at: "
        f"{missing_created}"
    )
    print(
        f"Artifacts with Missing updated_at: "
        f"{missing_updated}"
    )
    print(
        f"Artifacts with Missing URL: "
        f"{missing_url}"
    )

    status = (
        "PASSED"
        if (validation_passed and reload_passed)
        else "FAILED"
    )

    print(f"\nValidation Status: {status}")
    print(f"Saved Output Path: {output_path}")

    # --------------------------------------------------
    # SAMPLE ARTIFACTS
    # --------------------------------------------------

    print("\n" + "=" * 60)
    print("SAMPLE ARTIFACTS")
    print("=" * 60)

    sample_types = [
        "issue",
        "pull_request",
        "commit",
        "document",
    ]

    for artifact_type in sample_types:
        sample = next(
            (
                a for a in artifacts
                if a.artifact_type.value == artifact_type
            ),
            None,
        )

        if sample:
            print(f"\n--- Sample {artifact_type} ---")

            serialized = sample.model_dump(
                mode="json"
            )

            # Truncate content for readability.
            if (
                serialized.get("content")
                and len(serialized["content"]) > 200
            ):
                serialized["content"] = (
                    serialized["content"][:200]
                    + "..."
                )

            print(
                json.dumps(
                    serialized,
                    indent=2,
                    ensure_ascii=True,
                )
            )


# ============================================================
# MAIN
# ============================================================


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Normalize a raw GitHub dataset "
            "into universal Artifacts."
        )
    )

    parser.add_argument(
        "repository",
        help="Repository in owner/repo format",
    )

    args = parser.parse_args()

    repository_parts = (
        args.repository
        .strip("/")
        .split("/")
    )

    if len(repository_parts) != 2:
        raise ValueError(
            "Repository must use owner/repo format. "
            "Example: backstage/backstage"
        )

    owner, repo = repository_parts
    repository = f"{owner}/{repo}"

    # --------------------------------------------------
    # LOAD RAW DATASET
    # --------------------------------------------------

    print(
        f"\nLoading raw GitHub dataset: "
        f"{repository}"
    )

    dataset = load_github_dataset(
        owner=owner,
        repo=repo,
    )

    print(
        f"Repository: "
        f"{dataset['repository']['full_name']}"
    )

    # --------------------------------------------------
    # NORMALIZE
    # --------------------------------------------------

    artifacts, conflicts = normalize_dataset(
        dataset=dataset,
        repository=repository,
    )

    # --------------------------------------------------
    # VALIDATE
    # --------------------------------------------------

    print("\nValidating artifacts...")

    validation_passed, validation_errors = (
        validate_artifacts(artifacts)
    )

    if validation_errors:
        print("Validation errors:")
        for error in validation_errors:
            print(f"  - {error}")
    else:
        print("  All artifacts validated.")

    # --------------------------------------------------
    # SAVE
    # --------------------------------------------------

    output_directory = (
        NORMALIZED_DATA_DIRECTORY
        / owner
        / repo
    )

    output_directory.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_path = (
        output_directory / "artifacts.json"
    )

    print(f"\nSaving artifacts to: {output_path}")

    serialized_artifacts = [
        artifact.model_dump(mode="json")
        for artifact in artifacts
    ]

    with output_path.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            serialized_artifacts,
            file,
            indent=2,
            ensure_ascii=False,
        )

    print(
        f"  Saved {len(serialized_artifacts)} "
        f"artifacts."
    )

    # --------------------------------------------------
    # RELOAD AND VALIDATE
    # --------------------------------------------------

    print("\nReloading and validating saved file...")

    reload_passed, reload_errors = (
        validate_saved_file(
            file_path=output_path,
            original_artifacts=artifacts,
        )
    )

    if reload_errors:
        print("Reload validation errors:")
        for error in reload_errors:
            print(f"  - {error}")
    else:
        print("  Reload validation passed.")

    # --------------------------------------------------
    # STATISTICS
    # --------------------------------------------------

    print_statistics(
        artifacts=artifacts,
        conflicts=conflicts,
        validation_passed=validation_passed,
        reload_passed=reload_passed,
        output_path=output_path,
    )

    # --------------------------------------------------
    # FINAL STATUS
    # --------------------------------------------------

    if not (validation_passed and reload_passed):
        print("\nFAILED: Normalization did not pass "
              "all validation checks.")
        raise SystemExit(1)

    print("\nBatch 1 normalization complete.")


if __name__ == "__main__":
    main()
